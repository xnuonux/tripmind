export function paletteById(id) {
  return PALETTES.find((p) => p.id === id) || PALETTES[0];
}

export function samplePalette(pal, t) {
  const out = [0, 0, 0];
  for (let i = 0; i < 3; i++) {
    out[i] = pal.a[i] + pal.b[i] * Math.cos(6.28318530718 * (pal.c[i] * t + pal.d[i]));
  }
  return out;
}

export function flattenPalette(pal) {
  return new Float32Array([...pal.a, ...pal.b, ...pal.c, ...pal.d]);
}
